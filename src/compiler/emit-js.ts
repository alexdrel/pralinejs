import { elements, fragments, type ReadonlyXmlElement } from "@alexdrel/jsonml-ts";
import { stringifyJsonMl } from "@alexdrel/jsonml-ts/serialize";
import { type Blueprint, type HtmlModule } from "./model.ts";
import { Writer } from "./writer.ts";

type ExportGroup = Map<string, string | ExportGroup>;

function addExport(groups: Map<string, ExportGroup>, path: string, value: string): void {
  const parts = path.split(".");
  const root = parts.shift()!;
  const leaf = parts.pop()!;
  let group: ExportGroup = groups.get(root) ?? new Map();
  groups.set(root, group);
  for (const part of parts) {
    let child = group.get(part) as ExportGroup | undefined;
    if (!child) {
      child = new Map();
      group.set(part, child);
    }
    group = child;
  }
  group.set(leaf, value);
}

/** Construct reused values first, then assemble the public export objects. */
export function emitJs(module: HtmlModule): string {
  const out = new Writer();
  out.write("// Generated by Praline. Do not edit.");

  // The default value comes after the exports. Only references within named
  // blueprints need bindings before those export objects are assembled.
  const reused = new Set<string>();
  for (const blueprint of module.blueprints.values()) {
    for (const node of elements(fragments(blueprint.nodes), true)) {
      const path = module.templateNames.get(node);
      if (path) reused.add(path);
    }
  }
  const bindings = new Map<string, string>();
  const occupied = new Set<string>();
  for (const path of module.blueprints.keys()) occupied.add(path.split(".")[0]);
  let nextName = 0;
  for (const path of module.blueprints.keys()) {
    if (!path.includes(".")) {
      bindings.set(path, path);
    } else if (reused.has(path)) {
      let name: string;
      do name = `__praline${nextName++}`;
      while (occupied.has(name));
      bindings.set(path, name);
    }
  }

  const children = new Map<ReadonlyXmlElement, string>();
  for (const [node, path] of module.templateNames) {
    children.set(node, `...${bindings.get(path) ?? path}`);
  }

  function emitBlueprint(blueprint: Blueprint): string {
    return stringifyJsonMl(fragments(blueprint.nodes), { spaces: true, children, rootAsArray: true });
  }

  const groups = new Map<string, ExportGroup>();
  for (const [path, blueprint] of module.blueprints) {
    const name = bindings.get(path);
    if (name) {
      out.write(`${path.includes(".") ? "" : "export "}const ${name} = ${emitBlueprint(blueprint)};`, "");
    }
    if (!path.includes(".")) continue;

    addExport(groups, path, name ?? emitBlueprint(blueprint));
  }

  function writeMembers(group: ExportGroup): void {
    for (const [name, value] of group) {
      if (typeof value === "string") out.write(`${name}: ${value},`);
      else out.block(`${name}: {`, () => writeMembers(value), "},");
    }
  }

  for (const [name, group] of groups) {
    out.block(`export const ${name} = {`, () => writeMembers(group), "};");
    out.write("");
  }
  if (!module.namedOnly) out.write(`export default ${emitBlueprint(module.root)};`);
  return out.output;
}
