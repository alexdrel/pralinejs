import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, stat, utimes, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { writeIfChanged, writeOutput } from "./output.ts";
import { compileHtml } from "../compiler/index.ts";

test("source mode puts the hash in the generated-file notice after the DOM reference", async (t) => {
  const dir = await mkdtemp(join(tmpdir(), "praline-header-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const source = "<p>Text</p>";
  for (const format of ["js", "ts", "dts"] as const) {
    const { output } = await writeOutput(join(dir, "panel.html"), format, compileHtml(source, format), source, { update: "source" });
    assert.ok(output);
    const lines = (await readFile(output, "utf8")).split("\n");
    if (format !== "js") assert.equal(lines.shift(), '/// <reference lib="dom" />');
    assert.match(lines.shift()!, /^\/\/ Generated by Praline\. Source SHA-256: [a-f0-9]{64}$/);
    assert.doesNotMatch(lines.join("\n"), /Do not edit|SHA-256/);
  }
});

for (const format of ["js", "ts", "dts"] as const) {
  test(`source updates preserve edited ${format} output until HTML changes and recreate missing files`, async (t) => {
    const dir = await mkdtemp(join(tmpdir(), "praline-source-"));
    t.after(() => rm(dir, { recursive: true, force: true }));
    const input = join(dir, "panel.html");
    const notice = "// Generated by Praline. Do not edit.\n";
    const { output } = await writeOutput(input, format, notice + "generated", "<p>One</p>", { update: "source" });
    assert.ok(output);
    const original = await readFile(output, "utf8");
    assert.match(original, /^\/\/ Generated by Praline\. Source SHA-256: [a-f0-9]{64}\ngenerated$/);
    const edited = original.replace("generated", "user formatted and edited").replaceAll("\n", "\r\n");
    await writeFile(output, edited);
    await utimes(output, 1, 1);
    await writeOutput(input, format, notice + "compiler changed", "<p>One</p>", { update: "source" });
    assert.equal(await readFile(output, "utf8"), edited);
    assert.equal((await stat(output)).mtimeMs, 1000);

    await writeOutput(input, format, notice + "new generation", "<p>Two</p>", { update: "source" });
    const changed = await readFile(output, "utf8");
    assert.notEqual(changed.split("\n")[0], original.split("\n")[0]);
    assert.ok(changed.endsWith("\nnew generation"));
    await rm(output);
    await writeOutput(input, format, notice + "recreated", "<p>Two</p>", { update: "source" });
    assert.ok((await readFile(output, "utf8")).endsWith("\nrecreated"));

    await writeFile(output, "no source marker");
    await writeOutput(input, format, notice + "restored", "<p>Two</p>", { update: "source" });
    assert.ok((await readFile(output, "utf8")).endsWith("\nrestored"));
    await writeOutput(input, format, "exact default", "<p>Two</p>");
    assert.equal(await readFile(output, "utf8"), "exact default");
  });
}

test("unchanged generated files retain timestamps; changed files are updated", async (t) => {
  const dir = await mkdtemp(join(tmpdir(), "praline-files-"));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, "component.html.d.ts");
  assert.equal(await writeIfChanged(file, "first"), true);
  await utimes(file, 1, 1);
  const before = await stat(file);
  assert.equal(await writeIfChanged(file, "first"), false);
  assert.equal((await stat(file)).mtimeMs, before.mtimeMs);
  assert.equal(await writeIfChanged(file, "second"), true);
  assert.equal(await readFile(file, "utf8"), "second");
  assert.notEqual((await stat(file)).mtimeMs, before.mtimeMs);
});
