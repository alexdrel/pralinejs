import { createHash } from "node:crypto";
import { readFile, rm, writeFile } from "node:fs/promises";
import { type EmitFormat } from "../compiler/index.ts";

export type UpdateMode = "content" | "source";

type OutputOptions = { clean?: boolean; update?: UpdateMode };

export function outputPath(input: string, format: EmitFormat): string | undefined {
  if (format === "none") return undefined;
  return `${input}.${format === "dts" ? "d.ts" : format}`;
}

/** Write the selected format, then optionally remove the other generated counterparts. */
export async function writeOutput(
  input: string,
  format: EmitFormat,
  content: string,
  source: string,
  { clean = false, update = "content" }: OutputOptions = {},
): Promise<{ output: string | undefined; written: boolean }> {
  const output = outputPath(input, format);
  let written = false;
  if (output) {
    let unchangedSource = false;
    if (update === "source") {
      const hash = createHash("sha256").update(source).digest("hex");
      try {
        const previous = await readFile(output, "utf8");
        unchangedSource = previous.match(/^\/\/ Generated by Praline\. Source SHA-256: ([a-f0-9]{64})\r?$/m)?.[1] === hash;
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      }
      content = content.replace("// Generated by Praline. Do not edit.", `// Generated by Praline. Source SHA-256: ${hash}`);
    }
    if (!unchangedSource) written = await writeIfChanged(output, content);
  }
  if (clean) await cleanGenerated(input, output);
  return { output, written };
}

/** Remove known generated counterparts, optionally retaining the selected output path. */
export async function cleanGenerated(input: string, keep?: string): Promise<void> {
  for (const suffix of ["js", "ts", "d.ts"]) {
    const path = `${input}.${suffix}`;
    if (path !== keep) await rm(path, { force: true });
  }
}

/** Preserve timestamps and avoid development reloads when generated content is unchanged. */
export async function writeIfChanged(path: string, content: string): Promise<boolean> {
  try {
    if ((await readFile(path, "utf8")) === content) return false;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  await writeFile(path, content);
  return true;
}
